"""Check a film run against the runtime baseline's gates.

Reads a session's `timing.jsonl` (every run writes one; see
`src/util/timing_log.py`), measures what the gates in
`benchmarks/runtime/baseline.json` name — render tails as a ratio of the
clip's length, stalls, the queue margin, steering latency, first picture,
mid-film compiles, the browser's swaps — and prints one row per gate.
A gate the run has no data for (a text film renders nothing) is `n/a`; a
gate the timing log cannot measure (duplicate frames, the crossfade dip)
is left to the seam check and never reported as passing.

    python scripts/bench_report.py logs/sessions/<id> [--baseline <file>] [--json]
    python scripts/bench_report.py --readme          # the baseline table the README carries
    python scripts/bench_report.py --update-readme   # rewrite that table in README.md

Exit status: 0 no gate failed, 1 a gate failed, 2 the input could not be read.
"""

from __future__ import annotations

import argparse
import json
import math
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
BASELINE = REPO / "benchmarks" / "runtime" / "baseline.json"
README = REPO / "README.md"
README_START = "<!-- baseline:start (generated by scripts/bench_report.py --update-readme) -->"
README_END = "<!-- baseline:end -->"


# ── Statistics ──────────────────────────────────────────────────────

def percentile(values: list[float], q: float) -> float | None:
    """The q-th percentile (0-100), linear between closest ranks."""
    if not values:
        return None
    xs = sorted(values)
    pos = (len(xs) - 1) * q / 100.0
    lo, hi = math.floor(pos), math.ceil(pos)
    return xs[lo] + (xs[hi] - xs[lo]) * (pos - lo)


def summary(values: list[float]) -> dict:
    """n, mean, sd (population), p50, p95 and max; empty values give n = 0."""
    if not values:
        return {"n": 0}
    n = len(values)
    mean = sum(values) / n
    return {
        "n": n,
        "mean": mean,
        "sd": math.sqrt(sum((v - mean) ** 2 for v in values) / n),
        "p50": percentile(values, 50),
        "p95": percentile(values, 95),
        "max": max(values),
    }


def slope(values: list[float]) -> float | None:
    """Least-squares slope of `values` over their index (units per step)."""
    n = len(values)
    if n < 2:
        return None
    mx, my = (n - 1) / 2, sum(values) / n
    return sum((i - mx) * (v - my) for i, v in enumerate(values)) / sum((i - mx) ** 2 for i in range(n))


# ── Reading a run ───────────────────────────────────────────────────

def load_records(path: Path) -> list[dict]:
    """A session directory or its timing.jsonl."""
    if path.is_dir():
        path = path / "timing.jsonl"
    return [json.loads(line) for line in path.read_text(encoding="utf-8").splitlines() if line.strip()]


def measure(records: list[dict], *, warm_after: int = 3, stall_s: float = 0.05,
            compile_factor: float = 3.0) -> dict:
    """What the gates read, from one run's records. Renders and swaps count
    from the (`warm_after` + 1)-th clip; a stall is a consumer wait longer
    than `stall_s` after the first clip; a mid-film compile is a warm
    render longer than `compile_factor` times the warm median."""
    def of(event: str) -> list[dict]:
        return [r for r in records if r.get("event") == event]

    start = next(iter(of("session_start")), {})
    t0 = start.get("t", 0.0)

    playing = of("playing")
    on_air = {r["turn"]: r for r in playing}
    media = {r["turn"]: r["duration"] for r in of("enqueued")}

    renders = [r for r in of("render_done") if r.get("ok")]
    warm = renders[warm_after:]
    ratios = [r["render_s"] / media[r["turn"]] for r in warm if media.get(r["turn"])]
    walls = [r["render_s"] for r in warm]
    median = percentile(walls, 50)
    compiles = [r["turn"] for r in warm if median and r["render_s"] > compile_factor * median]
    off_media = [abs(on_air[r["turn"]]["duration"] - r["server"]["duration_s"]) * 1000
                 for r in renders
                 if r["turn"] in on_air and isinstance((r.get("server") or {}).get("duration_s"), (int, float))]

    stalls = [r for r in playing if not r.get("first") and r.get("waited", 0.0) > stall_s]
    margins = [r["margin"] for r in of("enqueued") if r.get("margin") is not None]

    received = {r["line"]: r["t"] for r in of("line_received")}
    landed: dict[int, int] = {}
    for r in of("line_landed"):
        for line in r["lines"]:
            landed[line] = r["turn"]
    dropped = sorted({line for r in of("line_dropped") for line in r["lines"]})
    steering = [on_air[turn]["t"] - received[line]
                for line, turn in sorted(landed.items()) if line in received and turn in on_air]

    ends = of("director_end")
    done = [r for r in ends if not r.get("cancelled") and "error" not in r]
    clips_per_beat: dict[int, int] = {}
    for r in done:
        clips_per_beat[r["clips"]] = clips_per_beat.get(r["clips"], 0) + 1

    swaps = [r for r in of("beacon") if r.get("kind") == "swap" and r.get("turn", 0) > warm_after]
    steady_swaps = [r["ms"] for r in swaps if r.get("prefetched") and r.get("armed") and "ms" in r]
    reloads = [r["turn"] for r in of("beacon")
               if r.get("kind") == "loadstart_on_playing" and r.get("turn", 0) > warm_after]

    return {
        "identity": {k: start.get(k) for k in ("session", "loop", "config", "story", "revision", "dirty",
                                                "video", "i2v_backend", "clip_seconds", "director_model",
                                                "director_service_tier")},
        "renders": {
            "n": len(renders),
            "failed": len([r for r in of("render_done") if not r.get("ok")]),
            "warm": len(warm),
            "render_s": summary(walls),
            "ratio": summary(ratios),
            "slope_ms_per_clip": slope(walls) * 1000 if len(walls) >= 2 else None,
            "mid_film_compiles": compiles,
            "hold_minus_media_ms": max(off_media) if off_media else None,
        },
        "director": {
            "calls": len(done),
            "cancelled": len([r for r in ends if r.get("cancelled")]),
            "errors": len([r for r in ends if "error" in r]),
            "retries": len([r for r in done if r.get("retry")]),
            "fallbacks": len([r for r in done if r.get("fallback")]),
            "plan_s": summary([r["plan_s"] for r in done]),
            "director_s": summary([r["director_s"] for r in done if "director_s" in r]),
            "answer_plan_s": summary([r["plan_s"] for r in done if r.get("input")]),
            "clips_per_beat": dict(sorted(clips_per_beat.items())),
        },
        "film": {
            "clips": len(playing),
            "stalls": len(stalls),
            "stalled_turns": [r["turn"] for r in stalls],
            "held_s": sum(r["waited"] for r in stalls),
            "min_queue_margin_s": min(margins) if margins else None,
            "first_picture_s": playing[0]["t"] - t0 if playing else None,
            "lines_received": len(received),
            "lines_landed": len(landed),
            "lines_dropped": dropped,
            "lines_unlanded": sorted(set(received) - set(landed) - set(dropped)),
            "steering_s": steering,
            "steering": summary(steering),
        },
        "seams": {
            "swaps": len(swaps),
            "swap_ms": summary(steady_swaps),
            "reloads_on_playing": len(reloads) if of("beacon") else None,
            "waiting": len([r for r in of("beacon") if r.get("kind") == "waiting"]),
        },
    }


# ── Gates ───────────────────────────────────────────────────────────

def _fmt(value, unit: str = "", digits: int = 3) -> str:
    if value is None:
        return "—"
    if isinstance(value, float):
        return f"{value:.{digits}f}{unit}"
    return f"{value}{unit}"


def evaluate(m: dict, gates: dict) -> list[dict]:
    """One row per gate: name, measured value, threshold, result
    (PASS / FAIL / n/a / not measured here) and a note."""
    renders, film, seams = m["renders"], m["film"], m["seams"]
    no_renders = "a text film renders nothing" if not m["identity"].get("video") else "no warm renders"
    values = {
        "render_ratio_p50": (renders["ratio"].get("p50"), no_renders),
        "render_ratio_p95": (renders["ratio"].get("p95"), no_renders),
        "render_ratio_max": (renders["ratio"].get("max"), no_renders),
        "render_slope_ms_per_clip": (renders["slope_ms_per_clip"], no_renders),
        "mid_film_compiles": (len(renders["mid_film_compiles"]) if renders["warm"] else None, no_renders),
        "stalls": (film["stalls"] if film["clips"] else None, "nothing played"),
        "min_queue_margin_s": (film["min_queue_margin_s"], "no clip was queued after playback began"),
        "steering_p50_s": (film["steering"].get("p50"), "no viewer line landed on a clip that played"),
        "steering_p95_s": (film["steering"].get("p95"), "no viewer line landed on a clip that played"),
        "first_picture_s": (film["first_picture_s"], "nothing played"),
        "swap_p95_ms": (seams["swap_ms"].get("p95"), "no steady-state swap beacons (no browser, or a text film)"),
        "reloads_on_playing": (seams["reloads_on_playing"], "no browser beacons"),
        "hold_minus_media_ms": (renders["hold_minus_media_ms"], "the renderer reports no clip duration"),
    }
    rows = []
    for name, gate in gates.items():
        if not isinstance(gate, dict):
            continue
        limit = f"≤ {gate['max']}" if "max" in gate else f"≥ {gate['min']}"
        if "measured_by" in gate:
            rows.append({"gate": name, "value": None, "threshold": limit, "result": "not measured here",
                         "note": gate["measured_by"]})
            continue
        value, why = values.get(name, (None, "the report does not know this gate"))
        note = ""
        if value is None:
            result, note = "n/a", why
        elif name == "render_slope_ms_per_clip" and renders["warm"] < gate.get("min_clips", 0):
            result, note = "n/a", f"needs ≥ {gate['min_clips']} warm clips, has {renders['warm']}"
        elif "max" in gate:
            result = "PASS" if value <= gate["max"] else "FAIL"
        else:
            result = "PASS" if value >= gate["min"] else "FAIL"
        if name == "stalls" and film["stalls"]:
            note = "turn " + ", ".join(map(str, film["stalled_turns"])) + f"; {film['held_s']:.2f} s held"
        if name == "mid_film_compiles" and renders["mid_film_compiles"]:
            note = "turn " + ", ".join(map(str, renders["mid_film_compiles"]))
        rows.append({"gate": name, "value": value, "threshold": limit, "result": result, "note": note})
    return rows


def render_text(m: dict, rows: list[dict]) -> str:
    ident, r, d, f = m["identity"], m["renders"], m["director"], m["film"]
    kind = f"video ({ident.get('i2v_backend')})" if ident.get("video") else "text film"
    revision = (ident.get("revision") or "unknown")[:10] + (" (dirty)" if ident.get("dirty") else "")
    out = [
        f"Session {ident.get('session')} · {ident.get('loop')} · config {ident.get('config')} · "
        f"revision {revision} · {kind} · {ident.get('clip_seconds')} s clips",
        f"Clips {f['clips']} · renders {r['n']} ({r['warm']} warm, {r['failed']} failed) · "
        f"Director calls {d['calls']} ({d['cancelled']} cancelled, {d['retries']} re-asked, {d['fallbacks']} fell back) · "
        f"lines {f['lines_received']} received, {f['lines_landed']} landed, {len(f['lines_dropped'])} dropped, "
        f"{len(f['lines_unlanded'])} never landed",
        "",
    ]
    width = max(len(row["gate"]) for row in rows) if rows else 10
    out.append(f"{'gate':<{width}}  {'value':>10}  {'threshold':>10}  result")
    for row in rows:
        line = f"{row['gate']:<{width}}  {_fmt(row['value']):>10}  {row['threshold']:>10}  {row['result']}"
        if row["note"]:
            line += f"  — {row['note']}"
        out.append(line)
    out.append("")
    if r["render_s"]["n"]:
        rs = r["render_s"]
        out.append(f"Render wall (warm): mean {rs['mean']:.3f} s, sd {rs['sd']:.3f}, p95 {rs['p95']:.3f}, max {rs['max']:.3f}")
    if d["plan_s"]["n"]:
        ps, ans = d["plan_s"], d["answer_plan_s"]
        line = f"Director plan: mean {ps['mean']:.2f} s, p95 {ps['p95']:.2f}, max {ps['max']:.2f}"
        if ans["n"]:
            line += f"; answering a line: mean {ans['mean']:.2f} s, max {ans['max']:.2f} (n = {ans['n']})"
        out.append(line)
        out.append("Clips per beat: " + ", ".join(f"{k}: {v}" for k, v in d["clips_per_beat"].items()))
    if f["steering_s"]:
        out.append("Steering latency (line received → its clip on air): " + ", ".join(f"{s:.2f} s" for s in f["steering_s"]))
    return "\n".join(out)


# ── The README's baseline table ─────────────────────────────────────

def readme_table(baseline: dict) -> str:
    """The baseline and its gates as the README shows them."""
    g, r, film, seams = baseline["gates"], baseline["renders"], baseline["film"], baseline["seams"]
    shape, recipe, director = baseline["shape"], baseline["recipe"], baseline["director"]
    steer = film["steering_s"]
    rows = [
        ("Render ratio p50 / p95 / max (render wall ÷ clip length)",
         f"{r['ratio']['p50']:.3f} / {r['ratio']['p95']:.3f} / {r['ratio']['max']:.3f}",
         f"≤ {g['render_ratio_p50']['max']:.2f} / {g['render_ratio_p95']['max']:.2f} / {g['render_ratio_max']['max']:.2f}"),
        (f"Render wall per {shape['delivered_seconds']:.2f} s clip",
         f"{r['render_s']['mean']:.2f} s mean, sd {r['render_s']['sd']:.3f} s, max {r['render_s']['max']:.2f} s "
         f"({r['n']} warm clips)", "—"),
        ("Render trend", f"{r['slope_ms_per_clip']:+.1f} ms per clip",
         f"≤ {g['render_slope_ms_per_clip']['max']:g} ms per clip over ≥ {g['render_slope_ms_per_clip']['min_clips']} clips"),
        ("Mid-film compiles", f"{r['mid_film_compiles']}", f"{g['mid_film_compiles']['max']}"),
        (f"Stalls (the picture waits > {g['stalls']['threshold_s']:g} s)", f"{film['stalls']}", f"{g['stalls']['max']}"),
        ("Minimum queue margin", f"{film['min_queue_margin_s']:.2f} s", f"≥ {g['min_queue_margin_s']['min']:g} s"),
        ("Steering latency (line → its clip on air)", f"{min(steer):.1f}-{max(steer):.1f} s (n = {len(steer)})",
         f"p50 ≤ {g['steering_p50_s']['max']:g} s, p95 ≤ {g['steering_p95_s']['max']:g} s"),
        ("First picture", f"{film['first_picture_s']:.1f} s", f"≤ {g['first_picture_s']['max']:g} s"),
        (f"Director call ({director['model']}, {director['service_tier']} tier)",
         f"{director['seconds']['mean']:.2f} s mean, p95 {director['seconds']['p95']:.2f} s", "—"),
        ("Browser swap", f"{seams['swap_ms']}", f"p95 ≤ {g['swap_p95_ms']['max']:g} ms"),
        ("Duplicate frames per seam", f"{seams['duplicate_frames_per_seam']}", f"{g['duplicate_frames_per_seam']['max']}"),
        ("Crossfade luminance dip", f"{seams['crossfade_dip']:.0%}", f"≤ {g['crossfade_dip']['max']:.0%}"),
    ]
    head = (f"Canonical setting: LTX-2.5 {recipe['variant']} ({recipe['sampling']}), {recipe['quant']}, "
            f"{recipe['compile']}, {shape['width']}×{shape['height']} at {shape['fps']} fps, "
            f"{shape['render_frames']} frames, client and server on one box: {baseline['hardware']['gpu']}. "
            f"Record: `benchmarks/runtime/baseline.json` ({baseline['label']}); "
            f"`python scripts/bench_report.py logs/sessions/<id>` checks a run against the gates.")
    lines = [head, "", "| Metric | Baseline | Gate |", "|---|---|---|"]
    lines += [f"| {a} | {b} | {c} |" for a, b, c in rows]
    lines += ["", f"*{baseline['provenance']}*"]
    return "\n".join(lines)


def readme_section(text: str) -> str | None:
    """The generated block currently in the README, or None without markers."""
    if README_START not in text or README_END not in text:
        return None
    return text.split(README_START, 1)[1].split(README_END, 1)[0].strip("\n")


def update_readme(baseline: dict, path: Path = README) -> bool:
    """Rewrite the generated block; True when the file changed."""
    text = path.read_text(encoding="utf-8")
    current = readme_section(text)
    if current is None:
        raise SystemExit(f"{path}: no {README_START} … {README_END} block")
    table = readme_table(baseline)
    if current == table:
        return False
    before, rest = text.split(README_START, 1)
    after = rest.split(README_END, 1)[1]
    path.write_text(f"{before}{README_START}\n{table}\n{README_END}{after}", encoding="utf-8")
    return True


# ── CLI ─────────────────────────────────────────────────────────────

def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("session", nargs="?", type=Path, help="logs/sessions/<id> or its timing.jsonl")
    ap.add_argument("--baseline", type=Path, default=BASELINE)
    ap.add_argument("--json", action="store_true", help="print the measurements and gate rows as JSON")
    ap.add_argument("--readme", action="store_true", help="print the README's baseline table")
    ap.add_argument("--update-readme", action="store_true", help="rewrite the baseline table in README.md")
    args = ap.parse_args(argv)

    try:
        baseline = json.loads(args.baseline.read_text(encoding="utf-8"))
    except (OSError, ValueError) as exc:
        print(f"cannot read the baseline {args.baseline}: {exc}", file=sys.stderr)
        return 2
    if args.readme:
        print(readme_table(baseline))
        return 0
    if args.update_readme:
        print("README.md updated" if update_readme(baseline) else "README.md already current")
        return 0
    if args.session is None:
        ap.error("a session directory or timing.jsonl is required")
    try:
        records = load_records(args.session)
    except (OSError, ValueError) as exc:
        print(f"cannot read {args.session}: {exc}", file=sys.stderr)
        return 2
    if not any(r.get("event") == "session_start" for r in records):
        print(f"{args.session}: no session_start record; not a timing log", file=sys.stderr)
        return 2

    gates = baseline["gates"]
    m = measure(records, warm_after=baseline.get("cold_warm", {}).get("warm_after_clips", 3),
                stall_s=gates["stalls"]["threshold_s"], compile_factor=gates["mid_film_compiles"]["factor"])
    rows = evaluate(m, gates)
    failed = [row["gate"] for row in rows if row["result"] == "FAIL"]
    if args.json:
        print(json.dumps({**m, "gates": rows, "failed": failed}, indent=2, ensure_ascii=False))
    else:
        print(render_text(m, rows))
        counts = {k: sum(row["result"] == k for row in rows) for k in ("PASS", "n/a", "not measured here")}
        tally = f"{counts['PASS']} passed, {counts['n/a']} n/a, {counts['not measured here']} not measured here"
        print(f"\nFAILED: {', '.join(failed)} ({tally})" if failed else f"\nNo gate failed ({tally}).")
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main())
